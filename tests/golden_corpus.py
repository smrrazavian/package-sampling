"""Read the R golden corpus and replay R's uniform stream (ADR-0006).

The corpus in ``tests/golden/`` is generated by ``tools/generate_goldens.R``
inside a container; regenerate it with::

    docker build -t r-parity tools/
    docker run --rm -v "$PWD/tools":/w r-parity Rscript /w/generate_goldens.R

Each design consumes uniforms one-for-one with its R counterpart, so feeding
the recorded draws back through :class:`ReplayRng` compares a Python sample to
an R sample value-for-value rather than only in distribution.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import numpy as np
from numpy.typing import NDArray

CORPUS = Path(__file__).parent / "golden" / "sampling_2.10.txt"


@dataclass
class Case:
    """One recorded R call."""

    name: str
    pik: NDArray[np.floating[Any]]
    out: NDArray[np.floating[Any]] | None = None
    u: NDArray[np.floating[Any]] | None = None
    extra: NDArray[np.floating[Any]] | None = None
    shape: tuple[int, int] | None = None
    error: str | None = None

    @property
    def raises(self) -> bool:
        return self.error is not None

    @property
    def matrix(self) -> NDArray[np.floating[Any]]:
        assert self.out is not None and self.shape is not None
        return self.out.reshape(self.shape)


class ReplayRng:
    """Yields a recorded uniform stream in place of a Generator.

    Only ``random`` is provided.  ``choice`` would mean R took a branch our
    port does not have, so it fails loudly instead of silently diverging.
    """

    def __init__(self, u: NDArray[np.floating[Any]]) -> None:
        self._u = np.asarray(u, dtype=float)
        self._i = 0

    def random(self, size: int | None = None) -> Any:
        n = 1 if size is None else int(size)
        if self._i + n > self._u.size:
            raise AssertionError(
                f"the port asked for {self._i + n} uniforms but R drew only "
                f"{self._u.size}: the two implementations consume the random "
                f"stream differently."
            )
        chunk = self._u[self._i : self._i + n]
        self._i += n
        return float(chunk[0]) if size is None else chunk

    def choice(self, *args: Any, **kwargs: Any) -> Any:
        raise AssertionError(
            "the port hit a fallback branch that R has no equivalent of; "
            "the recorded stream cannot describe it."
        )

    @property
    def exhausted(self) -> bool:
        return self._i == self._u.size


def _floats(line: str) -> NDArray[np.floating[Any]]:
    # R prints a missing value as NA; the NaN cases are deliberate corpus
    # entries (ERR_UPtillepi2_na), not corruption.
    return np.array(
        [np.nan if v == "NA" else float(v) for v in line.split()], dtype=float
    )


def load_cases(path: Path = CORPUS) -> dict[str, Case]:
    """Parse the corpus into ``{name: Case}``."""
    cases: dict[str, Case] = {}
    current: dict[str, Any] = {}

    def flush() -> None:
        if not current:
            return
        shape = current.get("shape")
        cases[current["name"]] = Case(
            name=current["name"],
            pik=current["pik"],
            out=current.get("out"),
            u=current.get("u"),
            extra=current.get("extra"),
            shape=(int(shape[0]), int(shape[1])) if shape is not None else None,
            error=current.get("error"),
        )

    for line in path.read_text().splitlines():
        if line.startswith("### "):
            flush()
            current = {"name": line[4:].strip()}
        elif line.startswith("error "):
            current["error"] = line[6:].strip()
        elif line.strip():
            key, _, rest = line.partition(" ")
            if key in ("pik", "out", "u", "extra", "shape"):
                current[key] = _floats(rest)
    flush()
    return cases
